package com.hydrocalc.app.calc

/**
 * Справочные данные калькулятора гидравлического расчёта трубопровода.
 * Методика и коэффициенты соответствуют онлайн-калькулятору prostobuild.by
 * (таблицы Шевелева, теоретическая гидравлика, СНиП 2.04.02-84).
 */

/** Метод расчёта */
enum class Method(val title: String) {
    SHEVELER("Таблицы Шевелева"),
    TEOR("Теоретическая гидравлика"),
    SNIP("СНиП 2.04.02-84")
}

/** Единицы расчётного расхода */
enum class FlowUnit(val title: String, val divisor: Double) {
    LPS("л/с", 1000.0),
    CUBIC_PER_HOUR("м³/час", 3600.0)
}

/** Коэффициенты формулы СНиП 2.04.02-84 */
data class SnipCoef(val m: Double, val a0: Double, val a1000: Double, val c: Double)

/**
 * Материалы трубопроводов.
 * tk, tm, tb  — показатели степени и множитель формулы Шевелева: 1000i = tk·(q^tb / d^tm)
 * m, a0, a1000, c — коэффициенты формулы СНиП 2.04.02-84:
 * 1000i = a1000/19.61 · ((a0 + c/v)^m / d^(m+1)) · v²
 */
enum class TubeMaterial(
    val title: String,
    val tk: Double, val tm: Double, val tb: Double,
    val snipM: Double, val snipA0: Double, val snipA1000: Double, val snipC: Double
) {
    STEEL_NEW(
        "Новые стальные без внутреннего защитного покрытия или с битумным защитным покрытием",
        1.790, 5.100, 1.900, 0.226, 1.0, 15.9, 0.684
    ),
    CAST_IRON_NEW(
        "Новые чугунные без внутреннего защитного покрытия или с битумным защитным покрытием",
        1.790, 5.100, 1.900, 0.284, 1.0, 14.4, 2.360
    ),
    STEEL_CAST_OLD(
        "Неновые стальные и чугунные без внутреннего защитного покрытия или с битумным защитным покрытием",
        1.735, 5.300, 2.000, 0.30, 1.0, 17.9, 0.867
    ),
    ASBESTOS_CEMENT(
        "Асбестоцементные",
        1.180, 4.890, 1.850, 0.19, 1.0, 11.0, 3.51
    ),
    REINFORCED_VIBRO(
        "Железобетонные виброгидропрессованные",
        1.688, 4.890, 1.850, 0.19, 1.0, 15.74, 3.51
    ),
    REINFORCED_CENTRIFUGED(
        "Железобетонные центрифугированные",
        1.486, 4.890, 1.850, 0.19, 1.0, 13.85, 3.51
    ),
    PLASTIC_COATED(
        "Стальные и чугунные с внутренним пластмассовым или полимерцементным покрытием, нанесённым методом центрифугирования",
        1.180, 4.890, 1.850, 0.19, 1.0, 11.00, 3.51
    ),
    CEMENT_SAND_SPRAYED(
        "Стальные и чугунные с внутренним цементно-песчаным покрытием, нанесённым методом набрызга",
        1.688, 4.890, 1.850, 0.19, 1.0, 15.74, 3.51
    ),
    CEMENT_SAND_CENTRIFUGED(
        "Стальные и чугунные с внутренним цементно-песчаным покрытием, нанесённым методом центрифугирования",
        1.486, 4.890, 1.850, 0.19, 1.0, 13.85, 3.51
    ),
    POLYMER(
        "Из полимерных материалов (пластмассовые)",
        1.052, 4.774, 1.774, 0.226, 0.0, 13.44, 1.0
    ),
    GLASS(
        "Стеклянные",
        1.144, 4.774, 1.774, 0.226, 0.0, 14.61, 1.0
    );

    /**
     * Коэффициенты СНиП для фактической скорости.
     * Для неновых стальных и чугунных труб таблица СНиП разделяется
     * по скорости: v ≤ 1,2 м/с и v > 1,2 м/с (как в исходном калькуляторе).
     */
    fun snipCoef(v: Double): SnipCoef = when (this) {
        STEEL_CAST_OLD ->
            if (v <= 1.2) SnipCoef(snipM, snipA0, 17.9, 0.867)
            else SnipCoef(snipM, snipA0, 21.0, 0.0)
        else -> SnipCoef(snipM, snipA0, snipA1000, snipC)
    }
}

/**
